"""UC_Citus scenarios: one tunnel and the schema for the run, the platform loaded per scenario, test datums dropped.

Needs the cluster (UC_Citus/deploy-citus.sh up). Measurements gathered by the steps are written to UC_Citus/<FEATURE>.md (one host) or
<FEATURE>-hosts.md (a host per node), e.g. ACID-hosts.md; a partial run writes *.partial.md.

@use_case Development/UseCase/UC_Citus
@facet Store
@status Proposed
"""
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import citus_plane as cp  # noqa: E402


def before_all(context):
    context.cluster = cp.Cluster.open()
    cp.two_workers(context.cluster)
    cp.clean_tests(context.cluster)
    context.measures = {}
    context.outcomes = []
    with context.cluster.connect(autocommit=True) as c:
        context.versions = c.execute("SELECT (SELECT extversion FROM pg_extension WHERE extname='citus'), "
                                     "(SELECT extversion FROM pg_extension WHERE extname='vector'), "
                                     "current_setting('server_version')").fetchone()


def before_feature(context, feature):
    if "lake" in feature.tags and context.cluster.admin(
            "SELECT count(*) FROM pg_extension WHERE extname = 'pg_lake_table'") != "1":
        feature.skip("no cold tier on this cluster (deploy-citus.sh lake-up)")


def after_scenario(context, scenario):
    for c in getattr(context, "open_conns", []):
        try:
            c.close()
        except Exception:
            pass
    context.open_conns = []
    try:
        if "hold" in scenario.tags:
            from steps.acid_steps import UNHOLD
            context.cluster.admin(UNHOLD)
    finally:
        cp.clean_tests(context.cluster)
    if "lake" in scenario.feature.tags:
        context.cluster.admin("DELETE FROM iq.event_cold")
    context.outcomes.append((scenario.name, scenario.status.name))


def after_feature(context, feature):
    _report(context, feature)
    context.outcomes.clear()            # in place: an attribute set in a feature hook is undone when the feature ends
    context.measures.clear()


def after_all(context):
    if hasattr(context, "cluster"):
        context.cluster.close()


TOPOLOGY = {"single": "a coordinator and two workers on one vc2-2c-4gb, by port (slice 1)",
            "hosts": "a coordinator and two workers on a vc2-2c-4gb each, over a Vultr VPC (slice 2)"}
TITLE = {"acid": "Citus against MarkLogic's transaction guarantees", "shacl": "SHACL enforced at commit on Citus",
         "inference": "Scoped inference at query time on Citus", "search": "BM25 over the distributed record",
         "gate": "The gate as the cluster's only writer", "backup": "Backups to Vultr, restorable to one moment",
         "tiered": "Hot Postgres, cold Iceberg on Citus", "domains": "The cluster's record, distributed by owner"}


def _report(context, feature):
    if not hasattr(context, "cluster") or not context.outcomes:      # nothing ran (a skipped feature)
        return
    citus, vector, pg = context.versions
    m = context.measures
    stem = Path(feature.filename).stem
    lines = ["# " + TITLE.get(stem, stem), "",
             "@use_case Development/UseCase/UC_Citus", "@facet Store", "",
             "Generated by `features/%s.feature` (%s) against the on-demand cluster on Vultr: PostgreSQL %s, "
             "Citus %s, pgvector %s; %s." % (stem, time.strftime("%Y-%m-%d"), pg, citus, vector,
                                            TOPOLOGY[context.cluster.mode]), "",
             "| Scenario | Result |", "|---|---|"]
    lines += ["| %s | %s |" % o for o in context.outcomes]
    if m:
        lines += ["", "## Measured", "", "| What | Value |", "|---|---|"]
        lines += ["| %s | %s |" % (k, v) for k, v in m.items()]
    name = stem.upper() + ("" if context.cluster.mode == "single" else "-hosts") + ".md"
    total = sum(1 for sc in feature.walk_scenarios())
    if len(context.outcomes) < total:                       # a partial run does not overwrite the report
        name = name.replace(".md", ".partial.md")
    (HERE.parent / name).write_text("\n".join(lines) + "\n")
