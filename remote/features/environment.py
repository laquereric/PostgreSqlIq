"""UC_Citus scenarios: one tunnel and the schema for the run, the platform loaded per scenario, test datums dropped.

Needs the cluster (UC_Citus/deploy-citus.sh up). Measurements gathered by the steps are written to UC_Citus/ACID.md.

@use_case Development/UseCase/UC_Citus
@facet Store
@status Proposed
"""
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import citus_plane as cp  # noqa: E402


def before_all(context):
    context.cluster = cp.Cluster.open()
    cp.two_workers(context.cluster)
    cp.clean_tests(context.cluster)
    context.measures = {}
    context.outcomes = []
    with context.cluster.connect(autocommit=True) as c:
        context.versions = c.execute("SELECT (SELECT extversion FROM pg_extension WHERE extname='citus'), "
                                     "(SELECT extversion FROM pg_extension WHERE extname='vector'), "
                                     "current_setting('server_version')").fetchone()


def after_scenario(context, scenario):
    for c in getattr(context, "open_conns", []):
        try:
            c.close()
        except Exception:
            pass
    context.open_conns = []
    cp.clean_tests(context.cluster)
    context.outcomes.append((scenario.name, scenario.status.name))


def after_all(context):
    if not hasattr(context, "cluster"):
        return
    try:
        _report(context)
    finally:
        context.cluster.close()


def _report(context):
    citus, vector, pg = context.versions
    m = context.measures
    lines = ["# Citus against MarkLogic's transaction guarantees", "",
             "@use_case Development/UseCase/UC_Citus", "@facet Store", "",
             "Generated by `features/acid.feature` (%s) against the on-demand cluster on Vultr: PostgreSQL %s, "
             "Citus %s, pgvector %s; a coordinator and two workers on one vc2-2c-4gb, a third worker added and "
             "removed by the last scenario." % (time.strftime("%Y-%m-%d"), pg, citus, vector), "",
             "| Scenario | Result |", "|---|---|"]
    lines += ["| %s | %s |" % o for o in context.outcomes]
    if m:
        lines += ["", "## Measured", "", "| What | Value |", "|---|---|"]
        lines += ["| %s | %s |" % (k, v) for k, v in m.items()]
    (HERE.parent / "ACID.md").write_text("\n".join(lines) + "\n")
